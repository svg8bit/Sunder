import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import solc from "solc";

const projectRoot = path.resolve(import.meta.dirname, "..");
const sourcePath = path.join(projectRoot, "contracts", "SunderFixedSupplyToken.sol");
const outputPath = path.join(projectRoot, "src", "evm", "generated", "sunder-fixed-supply-token.ts");
const source = await readFile(sourcePath, "utf8");

const input = {
  language: "Solidity",
  sources: {
    "SunderFixedSupplyToken.sol": { content: source },
  },
  settings: {
    optimizer: { enabled: true, runs: 1_000 },
    metadata: { bytecodeHash: "none" },
    outputSelection: {
      "*": { "*": ["abi", "evm.bytecode.object"] },
    },
  },
};

const compilation = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = Array.isArray(compilation.errors)
  ? compilation.errors.filter((entry) => entry.severity === "error")
  : [];

if (errors.length > 0) {
  throw new Error(errors.map((entry) => entry.formattedMessage).join("\n"));
}

const artifact = compilation.contracts?.["SunderFixedSupplyToken.sol"]?.SunderFixedSupplyToken;
if (!artifact?.abi || !artifact?.evm?.bytecode?.object) {
  throw new Error("Solidity compilation did not produce the expected ABI and bytecode.");
}

const generated = `// Generated by scripts/compile-evm-token.mjs from contracts/SunderFixedSupplyToken.sol.\n` +
  `// solc ${solc.version()}\n` +
  `export const SUNDER_FIXED_SUPPLY_TOKEN_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n` +
  `export const SUNDER_FIXED_SUPPLY_TOKEN_BYTECODE = "0x${artifact.evm.bytecode.object}" as const;\n`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, "utf8");
